-- Migracion: ficha de la impresora, «desde cuando» de su estado e historial del toner (ERP_SERCA docs/72,
-- paquete del 10/11/2026, mejoras 3, 6 y 7).
-- printer_printer: 4 columnas nullable, sin valores por defecto; las escribe el monitor de conectividad (y
-- «Comprobar») con la lectura IPP que ya hacia.
-- printer_toner_reading: una fila por consumible solo cuando cambia su nivel (pocas filas por cartucho);
-- el Worker borra las de mas de 400 dias una vez al dia. Al borrar una impresora se borran las suyas.
-- Antes de desplegar la version que las usa (Api y Worker leen las columnas en toda consulta de impresoras):
--   node scripts/sql/migraciones/aplicar.mjs scripts/sql/migraciones/2026-11-10-ficha-y-toner.sql
-- Repetirla no cambia nada.
-- Marcha atras:
--   DROP TABLE printer_toner_reading;
--   ALTER TABLE printer_printer DROP COLUMN ipp_state_since_utc, DROP COLUMN ipp_firmware,
--     DROP COLUMN ipp_up_since_utc, DROP COLUMN ipp_trays_json;
ALTER TABLE printer_printer
    ADD COLUMN IF NOT EXISTS ipp_state_since_utc timestamptz,
    ADD COLUMN IF NOT EXISTS ipp_firmware varchar(200),
    ADD COLUMN IF NOT EXISTS ipp_up_since_utc timestamptz,
    ADD COLUMN IF NOT EXISTS ipp_trays_json text;

CREATE TABLE IF NOT EXISTS printer_toner_reading (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    printer_id integer NOT NULL REFERENCES printer_printer (printer_id) ON DELETE CASCADE,
    marker integer NOT NULL,
    level integer NOT NULL,
    read_at_utc timestamptz NOT NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS ix_printer_toner_reading_printer_marker_read
    ON printer_toner_reading (printer_id, marker, read_at_utc);

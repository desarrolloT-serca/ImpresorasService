-- Migracion: contador de paginas de cada impresora, leido una vez al dia (ERP_SERCA docs/73, §5 opcion E).
-- printer_page_counter: el total acumulado que da la impresora a las 00:00 (zona de negocio) de cada dia, o en
-- cuanto responde si a esa hora no lo hace. Las paginas de un dia son la lectura del dia siguiente menos la suya.
-- toner_days_left: los dias que la Canon estima que le quedan al toner (su web, ERP_SERCA docs/72); null en el resto.
-- Una fila por impresora y dia (unas 20 al dia); no se borran. Al borrar una impresora se borran las suyas.
-- Antes de desplegar la version del Worker que la escribe:
--   node scripts/sql/migraciones/aplicar.mjs scripts/sql/migraciones/2026-11-10-contador-paginas.sql
-- Repetirla no cambia nada.
-- Marcha atras:
--   DROP TABLE printer_page_counter;
CREATE TABLE IF NOT EXISTS printer_page_counter (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    printer_id integer NOT NULL REFERENCES printer_printer (printer_id) ON DELETE CASCADE,
    business_day date NOT NULL,
    total_pages bigint NOT NULL,
    source varchar(20) NOT NULL,
    read_at_utc timestamptz NOT NULL,
    toner_days_left integer,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_printer_page_counter_printer_day
    ON printer_page_counter (printer_id, business_day);

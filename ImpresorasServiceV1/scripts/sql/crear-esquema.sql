-- PostgreSQL - esquema completo de ImpresorasService para una base de datos VACIA.
--
-- Sin nombre de esquema a proposito: las tablas se crean en el search_path de la sesion.
-- La forma prevista es scripts\crear-esquema.ps1, que toma el esquema del "Search Path" de
-- ConnectionStrings:PrintQueue (la misma cadena que usan Api y Worker), lo crea si falta y aplica
-- este fichero en UNA transaccion: o se crea todo o nada.
-- A mano:  psql ... -v ON_ERROR_STOP=1 -1 -c "SET search_path TO impresoras" -f crear-esquema.sql
--
-- Tipos:
--   Fechas -> varchar(26). herencia-hana: el modelo EF convierte TODO DateTimeOffset a texto
--   "yyyy-MM-dd HH:mm:ss" (ver ImpresorasDbContext) y Npgsql no deja meter texto
--   en una columna timestamp. Es el mismo formato que ya ejercitan los tests en SQLite, y al ser
--   ISO de ancho fijo en UTC ordena y compara bien como texto. Pasar a timestamptz exige quitar
--   esos converters y revisar que todo DateTimeOffset llegue con offset 0.
--   IDENTITY en las 5 claves que genera la base de datos (EF las espera: ValueGeneratedOnAdd).
--
-- Usuarios: no se siembran aqui (el hash es BCrypt). El primero se crea con POST /bootstrap/first-admin,
-- que solo responde en Development con Bootstrap:EnableFirstAdminEndpoint=true: arrancar la Api en
-- local apuntando a la BD nueva, crearlo y apagarla.
-- printer_dashboard_threshold y printer_telegram_config los crea la aplicacion al primer uso.

CREATE TABLE printer_store (
    store_id integer NOT NULL,
    name varchar(120) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at_utc varchar(26) NOT NULL,
    updated_at_utc varchar(26) NOT NULL,
    PRIMARY KEY (store_id)
);
CREATE INDEX ix_printer_store_name ON printer_store (name);

CREATE TABLE printer_printer (
    printer_id integer GENERATED BY DEFAULT AS IDENTITY,
    printer_name varchar(120) NOT NULL,
    spool_queue varchar(200) NOT NULL,
    host varchar(255),
    store_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    capabilities_json text,
    created_at_utc varchar(26) NOT NULL,
    updated_at_utc varchar(26) NOT NULL,
    connection_failures_streak integer NOT NULL DEFAULT 0,
    last_connection_ok boolean,
    last_connection_check_at_utc varchar(26),
    last_connection_transport varchar(40),
    last_connection_error varchar(400),
    ipp_supported boolean,
    PRIMARY KEY (printer_id)
);
CREATE UNIQUE INDEX ix_printer_printer_store_id_spool_queue ON printer_printer (store_id, spool_queue);

CREATE TABLE printer_routing_rule (
    rule_id integer GENERATED BY DEFAULT AS IDENTITY,
    priority integer NOT NULL,
    store_id integer,
    document_type varchar(80),
    channel varchar(40),
    printer_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    valid_from_utc varchar(26) NOT NULL,
    valid_to_utc varchar(26),
    created_by varchar(120) NOT NULL,
    created_at_utc varchar(26) NOT NULL,
    updated_at_utc varchar(26) NOT NULL,
    PRIMARY KEY (rule_id)
);
CREATE INDEX ix_printer_routing_rule_resolve ON printer_routing_rule (is_active, priority, store_id, document_type, channel);

-- Entrada de trabajos: la escribe el ERP. Basta con
--   INSERT INTO printer_source_print_job (external_job_id, store_id, document_type, pdf_blob)
-- external_job_id identifica el trabajo, no el albaran: si se repite, se descarta como duplicado,
-- asi que una reimpresion necesita un id nuevo. Lo demas lo rellenan los DEFAULT y el Worker.
CREATE TABLE printer_source_print_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    source_system varchar(50) NOT NULL DEFAULT 'ERP',
    external_job_id varchar(120) NOT NULL,
    store_id integer NOT NULL,
    document_type varchar(80) NOT NULL,
    channel varchar(40),
    pdf_blob bytea,
    created_at_utc varchar(26) NOT NULL DEFAULT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'),
    is_processed boolean NOT NULL DEFAULT FALSE,
    claimed_by varchar(200),
    claimed_until_utc varchar(26),
    claim_token varchar(64),
    PRIMARY KEY (id)
);
CREATE INDEX ix_printer_source_print_job_processed_created ON printer_source_print_job (is_processed, created_at_utc);
CREATE INDEX ix_printer_source_print_job_processed_claimed_id ON printer_source_print_job (is_processed, claimed_until_utc, id);

CREATE TABLE printer_print_job (
    job_id bytea NOT NULL,
    source_system varchar(50) NOT NULL,
    external_job_id varchar(120) NOT NULL,
    store_id integer NOT NULL,
    document_type varchar(80) NOT NULL,
    channel varchar(40) NOT NULL DEFAULT 'DEFAULT',
    pdf_blob bytea,
    pdf_sha256 varchar(64) NOT NULL,
    status varchar(40) NOT NULL,
    printer_id integer,
    attempt_count integer NOT NULL DEFAULT 0,
    next_retry_at_utc varchar(26),
    last_error_code varchar(60),
    last_error_message varchar(1000),
    correlation_id bytea NOT NULL,
    created_at_utc varchar(26) NOT NULL,
    updated_at_utc varchar(26) NOT NULL,
    row_version bytea,
    PRIMARY KEY (job_id)
);
CREATE UNIQUE INDEX ix_printer_print_job_source_external ON printer_print_job (source_system, external_job_id);
CREATE INDEX ix_printer_print_job_status_next_retry ON printer_print_job (status, next_retry_at_utc);

CREATE TABLE printer_print_job_event (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY,
    job_id bytea NOT NULL,
    event_type varchar(60) NOT NULL,
    old_status varchar(40),
    new_status varchar(40),
    error_code varchar(60),
    message varchar(1000),
    actor_type varchar(30) NOT NULL,
    actor_id varchar(120),
    metadata_json text,
    occurred_at_utc varchar(26) NOT NULL,
    PRIMARY KEY (event_id)
);
CREATE INDEX ix_printer_print_job_event_job_occurred ON printer_print_job_event (job_id, occurred_at_utc);

CREATE TABLE printer_user (
    user_id integer GENERATED BY DEFAULT AS IDENTITY,
    login varchar(80) NOT NULL,
    password_hash varchar(256) NOT NULL,
    role varchar(40) NOT NULL,
    store_id integer,
    display_name varchar(120),
    is_active boolean NOT NULL DEFAULT TRUE,
    token_version integer NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id)
);
CREATE UNIQUE INDEX ix_printer_user_login ON printer_user (login);

CREATE TABLE printer_dashboard_threshold (
    id integer NOT NULL,
    warning_queue_min integer NOT NULL DEFAULT 10,
    critical_queue_min integer NOT NULL DEFAULT 30,
    queue_warning_severity varchar(32) NOT NULL DEFAULT 'warning',
    queue_critical_severity varchar(32) NOT NULL DEFAULT 'critical',
    warning_failed_without_retry_min integer NOT NULL DEFAULT 1,
    critical_failed_without_retry_min integer NOT NULL DEFAULT 5,
    failed_warning_severity varchar(32) NOT NULL DEFAULT 'warning',
    failed_critical_severity varchar(32) NOT NULL DEFAULT 'critical',
    missing_host_min integer NOT NULL DEFAULT 1,
    missing_host_severity varchar(32) NOT NULL DEFAULT 'warning',
    conn_warning_failures_min integer NOT NULL DEFAULT 2,
    conn_critical_failures_min integer NOT NULL DEFAULT 3,
    conn_warning_severity varchar(32) NOT NULL DEFAULT 'warning',
    conn_critical_severity varchar(32) NOT NULL DEFAULT 'critical',
    updated_at_utc varchar(26) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE printer_telegram_config (
    id integer NOT NULL,
    min_severity varchar(20) NOT NULL DEFAULT 'critical',
    notify_on_recovery boolean NOT NULL DEFAULT TRUE,
    check_interval_minutes integer NOT NULL DEFAULT 5,
    updated_at_utc varchar(26) NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE printer_telegram_chat (
    chat_id bigint NOT NULL,
    description varchar(120),
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at_utc varchar(26) NOT NULL,
    store_id integer,
    PRIMARY KEY (chat_id)
);

CREATE TABLE printer_alert_state (
    store_id integer NOT NULL,
    last_health varchar(20) NOT NULL DEFAULT 'healthy',
    notified_health varchar(20),
    notified_at_utc varchar(26),
    checked_at_utc varchar(26) NOT NULL,
    PRIMARY KEY (store_id)
);

CREATE TABLE printer_worker_lock (
    id integer NOT NULL,
    holder varchar(200),
    heartbeat_utc varchar(26) NOT NULL,
    PRIMARY KEY (id)
);

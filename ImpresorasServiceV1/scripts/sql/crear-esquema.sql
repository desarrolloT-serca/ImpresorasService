-- PostgreSQL - esquema completo de ImpresorasService para una base de datos VACIA.
--
-- Sin nombre de esquema a proposito: las tablas se crean en el search_path de la sesion.
-- La forma prevista es scripts\crear-esquema.ps1, que toma el esquema del "Search Path" de
-- ConnectionStrings:PrintQueue (la misma cadena que usan Api y Worker), lo crea si falta y aplica
-- este fichero en UNA transaccion: o se crea todo o nada.
-- A mano:  psql ... -v ON_ERROR_STOP=1 -1 -c "SET search_path TO impresoras" -f crear-esquema.sql
--
-- Tipos:
--   Fechas -> timestamptz. La aplicacion escribe siempre en UTC (ImpresorasDbContext normaliza
--   cualquier DateTimeOffset con otro offset antes de enviarlo).
--   IDENTITY en las 5 claves que genera la base de datos (EF las espera: ValueGeneratedOnAdd).
--
-- Sin usuarios propios: se entra solo con el pase del ERP (Erp:Secret). Las tiendas son los almacenes
-- del ERP: printer_store es una vista sobre gesserca.fdalmacen (11/11/2026, ERP_SERCA docs/72).
-- printer_dashboard_threshold y printer_telegram_config los crea la aplicacion al primer uso.

-- EXCEPCION a "sin nombre de esquema": fdalmacen es del ERP y vive siempre en gesserca. Por eso el
-- servicio solo se instala en la base del ERP. Solo lectura: el alta y la baja se hacen en el ERP.
-- La vista lee fdalmacen con los permisos de su dueno: el usuario del servicio necesita SELECT sobre
-- printer_store (GRANT aparte, como el resto de tablas), no sobre gesserca.
CREATE VIEW printer_store AS
SELECT cod_alm::integer AS store_id,
       rtrim(denominacion)::varchar(120) AS name,
       fec_baja IS NULL AS is_active
FROM gesserca.fdalmacen;

CREATE TABLE printer_printer (
    printer_id integer GENERATED BY DEFAULT AS IDENTITY,
    printer_name varchar(120) NOT NULL,
    spool_queue varchar(200),
    host varchar(255),
    store_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    capabilities_json text,
    created_at_utc timestamptz NOT NULL,
    updated_at_utc timestamptz NOT NULL,
    connection_failures_streak integer NOT NULL DEFAULT 0,
    last_connection_ok boolean,
    last_connection_check_at_utc timestamptz,
    last_connection_transport varchar(40),
    last_connection_error varchar(400),
    connection_failing_since_utc timestamptz,
    ipp_supported boolean,
    -- Ultimo estado IPP (monitor de conectividad, cada 30 s): ERP_SERCA docs/72, R1.
    ipp_state integer,
    ipp_state_reasons varchar(400),
    ipp_state_message varchar(400),
    ipp_queued_jobs integer,
    ipp_markers_json text,
    ipp_make_and_model varchar(200),
    ipp_more_info_url varchar(400),
    ipp_checked_at_utc timestamptz,
    -- Ficha y «desde cuando» del estado: ERP_SERCA docs/72, mejoras 3 y 6.
    ipp_state_since_utc timestamptz,
    ipp_firmware varchar(200),
    ipp_up_since_utc timestamptz,
    ipp_trays_json text,
    PRIMARY KEY (printer_id)
);
CREATE UNIQUE INDEX ix_printer_printer_store_id_spool_queue ON printer_printer (store_id, spool_queue);

-- Contador de paginas acumulado, una lectura por impresora y dia a las 00:00 (ERP_SERCA docs/73, opcion E).
CREATE TABLE printer_page_counter (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    printer_id integer NOT NULL REFERENCES printer_printer (printer_id) ON DELETE CASCADE,
    business_day date NOT NULL,
    total_pages bigint NOT NULL,
    source varchar(20) NOT NULL,
    read_at_utc timestamptz NOT NULL,
    toner_days_left integer,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX ix_printer_page_counter_printer_day ON printer_page_counter (printer_id, business_day);

CREATE TABLE printer_routing_rule (
    rule_id integer GENERATED BY DEFAULT AS IDENTITY,
    priority integer NOT NULL,
    store_id integer,
    document_type varchar(80),
    channel varchar(40),
    printer_id integer NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    valid_from_utc timestamptz NOT NULL,
    valid_to_utc timestamptz,
    created_by varchar(120) NOT NULL,
    created_at_utc timestamptz NOT NULL,

namespace ImpresorasService.Infrastructure;

/// <summary>
/// PDF mínimo válido (~67 bytes) para pruebas cuando no se proporciona un PDF real.
/// Estructura: %PDF-1. + trailer con Catalog/Pages/Page/MediaBox.
/// </summary>
public static class MinimalPdf
{
    /// <summary>
    /// Bytes de un PDF mínimo válido que la mayoría de visores pueden abrir.
    /// </summary>
    public static readonly byte[] Bytes =
    [
        0x25, 0x50, 0x44, 0x46, 0x2D, 0x31, 0x2E, 0x0D, // %PDF-1.\r
        0x74, 0x72, 0x61, 0x69, 0x6C, 0x65, 0x72, 0x3C, // trailer<
        0x3C, 0x2F, 0x52, 0x6F, 0x6F, 0x74, 0x3C, 0x3C, // </Root<<
        0x2F, 0x50, 0x61, 0x67, 0x65, 0x73, 0x3C, 0x3C, // /Pages<<
        0x2F, 0x4B, 0x69, 0x64, 0x73, 0x5B, 0x3C, 0x3C, // /Kids[<<
        0x2F, 0x4D, 0x65, 0x64, 0x69, 0x61, 0x42, 0x6F, // /MediaBo
        0x78, 0x5B, 0x30, 0x20, 0x30, 0x20, 0x33, 0x20, // x[0 0 3 
        0x33, 0x5D, 0x3E, 0x3E, 0x5D, 0x3E, 0x3E, 0x3E, // 3]>>]>>>
        0x3E, 0x3E, 0x3E                          // >>>
    ];
}
